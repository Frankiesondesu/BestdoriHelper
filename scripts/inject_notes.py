def main() -> int:
    changed = []
    for num, note in sorted(NOTES.items()):
        path = SLIDES / f"{num:02d}.slide"
        if not path.exists():
            print(f"✗ 找不到 {path.name}")
            continue
        text = path.read_text(encoding="utf-8")

        # 去掉已有的 notes（幂等，可重复跑）
        text = re.sub(r"\s*notes=\{`[\s\S]*?`\}", "", text, count=1)

        # 在 <Slide ...> 的开标签里插入 notes
        m = re.search(r"<Slide\b[^>]*>", text)
        if not m:
            print(f"✗ {path.name} 里找不到 <Slide> 开标签")
            continue
        tag = m.group(0)
        # notes 里避免出现反引号，防止破坏模板字符串
        safe = note.replace("`", "'")
        new_tag = tag[:-1] + " notes={`" + safe + "`}>"
        text = text[:m.start()] + new_tag + text[m.end():]
        path.write_text(text, encoding="utf-8")
        changed.append(num)

    print(f"已写入讲者备注：{len(changed)} 页 -> {changed}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
